from __future__ import annotations

from datetime import datetime
from html import escape
from typing import Any

from .scenarios import get_scenario
from .store import Store


def _fmt_dt(value: str | None) -> str:
    if not value:
        return "—"
    try:
        dt = datetime.fromisoformat(value.replace("Z", "+00:00"))
        return dt.astimezone().strftime("%Y-%m-%d %H:%M")
    except Exception:
        return value


def build_report(store: Store, experiment_id: int | None) -> str:
    if not experiment_id:
        return "# WorkspaceLab 實驗報告\n\n尚未執行實驗。\n"
    exp = store.get_experiment(experiment_id)
    if not exp:
        return "# WorkspaceLab 實驗報告\n\n找不到實驗。\n"
    sc = get_scenario(exp["scenario"])
    actions = store.list_actions(experiment_id)
    metrics = store.list_metrics(experiment_id)
    events = store.list_events(experiment_id)
    errors = [a for a in actions if a["status"] == "error"]
    dry = [a for a in actions if a["status"] == "dry_run"]
    metric_map = {m["key"]: m for m in metrics}

    lines = [
        "# WorkspaceLab 實驗報告",
        "",
        f"- 實驗：{exp['name']}",
        f"- 場景：{sc['name']}（{sc['pain']} → {sc['gain']}）",
        f"- 模式：{exp['mode']}",
        f"- 狀態：{exp['status']}",
        f"- 開始：{_fmt_dt(exp.get('started_at'))}",
        f"- 結束：{_fmt_dt(exp.get('ended_at'))}",
        f"- 動作：{len(actions)}（成功 {len(actions)-len(errors)-len(dry)}、dry-run {len(dry)}、失敗 {len(errors)}）",
        "",
        "## KPI",
        "",
        "| 指標 | 數值 | 單位 |",
        "|---|---:|---|",
    ]
    if metrics:
        for m in metrics:
            lines.append(f"| {m['key']} | {m['value']:.2f} | {m['unit']} |")
    else:
        lines.append("| — | — | — |")

    lines += ["", "## 事件", ""]
    if events:
        for e in events:
            lines.append(f"- `{_fmt_dt(e['created_at'])}` **{e['type']}**：{e['payload']}")
    else:
        lines.append("- 無")

    lines += ["", "## 時間軸", "", "| 時間 | 角色 | Agent | 工具 | 目標 | 狀態 | 摘要 |", "|---|---|---|---|---|---|---|"]
    for a in actions:
        lines.append(
            f"| {_fmt_dt(a['created_at'])} | {a['actor']} | {a['agent']} | {a['tool']} | "
            f"{a['target']} | {a['status']} | {a['summary'][:80]} |"
        )

    lines += ["", "## 失敗與限制", ""]
    if errors:
        for e in errors[:10]:
            lines.append(f"- **{e['tool']} / {e['actor']}**：{e['error'] or '未知錯誤'}")
    else:
        lines.append("- 無失敗動作。")
    if dry:
        lines.append(f"- {len(dry)} 個動作是 dry-run；Real 模式需關閉 `DRY_RUN` 才會真的執行。")
    lines.append("- Chat 使用者訊息、Meet 錄影／逐字稿、Gemini in Apps UI、AppSheet 建立不在本版範圍。")

    lines += [
        "", "## 建議", "",
        f"1. 先用 Mock 模式把「{sc['name']}」腳本跑順，確認角色、順序、KPI。",
        "2. Real 模式先保持 `DRY_RUN=1`，確認 allowlist 與 service account 權限。",
        "3. 只對測試 OU／測試信箱執行；不要寄給真實客戶。",
        "4. 第二階段再補 Chat／Meet／Gemini UI 的瀏覽器自動化。",
        "", "---", f"*Generated by WorkspaceLab · {datetime.now().strftime('%Y-%m-%d %H:%M')}*",
    ]
    return "\n".join(lines)


def build_html_report(store: Store, experiment_id: int | None) -> str:
    md = build_report(store, experiment_id)
    return f"""<!DOCTYPE html>
<html lang="zh-Hant"><head><meta charset="UTF-8"><title>WorkspaceLab 實驗報告</title>
<style>body{{background:#0b1220;color:#e8eef7;font-family:"PingFang TC","Noto Sans TC",sans-serif;margin:0;padding:40px}}
.wrap{{max-width:1000px;margin:0 auto}}pre{{white-space:pre-wrap;line-height:1.7;background:#101b2c;border:1px solid rgba(255,255,255,.12);border-radius:12px;padding:24px;font-family:"SFMono-Regular",Menlo,monospace;font-size:12px}}
h1{{font-size:20px}}</style></head><body><div class="wrap"><h1>WorkspaceLab 實驗報告</h1><pre>{escape(md)}</pre></div></body></html>"""
